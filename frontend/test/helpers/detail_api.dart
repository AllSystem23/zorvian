/// Respuestas de la API para montar **pantallas de detalle** en tests.
///
/// Las páginas de detalle hacen `dio.get(<recurso>/<id>)` en `initState` y
/// pintan sus datos sin defensas: si el JSON no trae las claves obligatorias
/// (por ejemplo `createdAt` o `clientId`) la página cae en su estado de error y
/// el test solo validaría un mensaje, no el layout real. Estas respuestas
/// respetan los modelos (`QuoteDetail`, `PurchaseDetail`, `CreditDetail`…).
///
/// Uso:
/// ```dart
/// final api = detailApi({'credits/cr1/late-fees': []});
/// ```
