    // Cualquier endpoint secundario (pagos, acciones de cobro, catálogos) sin
    // respuesta explícita devuelve una página vacía.
    fallback: const {'items': [], 'totalCount': 0, 'page': 1, 'pageSize': 50, 'totalPages': 0},
  );
}

